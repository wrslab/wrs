# JS KeyboardEvent names -> symbols above.  Printable keys arrive as the
# character itself and are handled by ord() in `symbol_from_name`.
_NAMED = {
    'ArrowDown': DOWN, 'ArrowUp': UP, 'ArrowLeft': LEFT, 'ArrowRight': RIGHT,
    'Backspace': BACKSPACE, 'CapsLock': CAPSLOCK, 'Delete': DELETE,
    'End': END, 'Enter': ENTER, 'Escape': ESCAPE, 'Home': HOME,
    'Insert': INSERT, 'NumLock': NUMLOCK, 'PageDown': PAGEDOWN,
    'PageUp': PAGEUP, 'Pause': PAUSE, 'PrintScreen': PRINT,
    'ScrollLock': SCROLLLOCK, 'Tab': TAB,
    'Alt': LALT, 'Control': LCTRL, 'Shift': LSHIFT, 'Meta': LWINDOWS,
}
_NAMED.update({f'F{i}': globals()[f'F{i}'] for i in range(1, 13)})


def symbol_from_name(name):
    """rendercanvas key name -> key symbol, or None if unmapped."""
    if name in _NAMED:
        return _NAMED[name]
    if len(name) == 1:
        return ord(name.lower())
    return None
